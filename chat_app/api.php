<?php
header('Content-Type: application/json');
header('Access-Control-Allow-Origin: *');

// デバッグ用ログ
error_log('APIリクエスト受信: ' . file_get_contents('php://input'));

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $input = json_decode(file_get_contents('php://input'), true);
    $user_message = $input['message'] ?? '';
    
    error_log('受信メッセージ: ' . $user_message);
    
    if (empty($user_message)) {
        error_log('メッセージが空です');
        echo json_encode(['error' => 'メッセージが空です']);
        exit;
    }
    
    // qwen2.5モデル用の日本語指示プロンプト
    $prompt = "あなたは日本語のアシスタントです。以下のルールを守ってください：

1. 必ず日本語で回答する
2. 親切で丁寧な日本語を使用する
3. ユーザーの質問に適切に回答する

ユーザー: " . $user_message . "
アシスタント:";
    
    $data = [
        'model' => 'qwen2.5:0.5b', // 新しくダウンロードしたモデル
        'prompt' => $prompt,
        'stream' => false,
        'options' => [
            'temperature' => 0.7,
            'top_p' => 0.9
        ]
    ];
    
    $ch = curl_init();
    curl_setopt($ch, CURLOPT_URL, 'http://localhost:11434/api/generate');
    curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
    curl_setopt($ch, CURLOPT_POST, true);
    curl_setopt($ch, CURLOPT_POSTFIELDS, json_encode($data));
    curl_setopt($ch, CURLOPT_HTTPHEADER, ['Content-Type: application/json']);
    curl_setopt($ch, CURLOPT_TIMEOUT, 30);
    
    $response = curl_exec($ch);
    $http_code = curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    
    if ($http_code === 200 && $response) {
        $result = json_decode($response, true);
        $ai_response = $result['response'] ?? '申し訳ありません。回答を生成できませんでした。';
        
        // 英語が含まれている場合はフォールバック応答を使用
        if (preg_match('/[a-zA-Z]/', $ai_response)) {
            $ai_response = generateFallbackResponse($user_message);
        }
    } else {
        // フォールバック応答
        $ai_response = generateFallbackResponse($user_message);
    }
    
    echo json_encode(['response' => $ai_response]);
} else {
    echo json_encode(['error' => 'POSTメソッドのみ対応しています']);
}

